from fastapi import APIRouter, HTTPException, status
from app.schemas.agent import ChatRequest
from app.agents.graph import graph
from langchain_core.messages import HumanMessage

router = APIRouter()

@router.post("/chat", status_code=status.HTTP_200_OK)
async def trigger_agent_workflow(payload: ChatRequest):
    """
    Accepts arbitrary frontend process configurations, triggers the unified LangGraph 
    state engine orchestration pipeline, and delivers runtime outputs.
    """
    try:
        # 1. Package the process type and thread state into LangGraph config
        config = {
            "configurable": {
                "thread_id": payload.thread_id,
                "process_type": payload.process_type  # This triggers the routing behavior inside nodes.py
            }
        }
        
        # 2. Structure initial state payload with the user message object
        initial_state = {
            "messages": [HumanMessage(content=payload.message)]
        }
        
        # 3. Trigger LangGraph execution asynchronously
        final_state = await graph.ainvoke(initial_state, config=config)
        
        # 4. Extract the last message generated by your LLM node
        last_message = final_state["messages"][-1]
        
        return {
            "status": "success",
            "active_process": payload.process_type,
            "response": last_message.content
        }
        
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to process agent workflow execution stream: {str(e)}"
        )
