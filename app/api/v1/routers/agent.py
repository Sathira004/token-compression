from fastapi import APIRouter, BackgroundTasks, HTTPException, Request, status
from app.schemas.agent import ChatRequest
from app.agents.graph import graph
from langchain_core.messages import HumanMessage
from app.services.run_service import get_run_id, persist_and_evaluate_run
from time import perf_counter
from app.services.token_usage_service import phase_usage

router = APIRouter()

@router.post("/chat", status_code=status.HTTP_200_OK)
async def trigger_agent_workflow(
    payload: ChatRequest,
    request: Request,
    background_tasks: BackgroundTasks,
):
    """
    Accepts arbitrary frontend process configurations, triggers the unified LangGraph
    state engine orchestration pipeline, and delivers runtime outputs.
    """

    print(f"Received payload: {payload}")

    try:
        started_at = perf_counter()
        # 1. Package the process type and thread state into LangGraph config
        config = {
            "configurable": {
                "thread_id": payload.thread_id,
                "process_type": payload.process_type  # This triggers the routing behavior inside nodes.py
            }
        }
        
        # 2. Structure initial state payload with the user message object
        initial_state = {
            "messages": [HumanMessage(content=payload.message)]
        }
        
        # 3. Trigger LangGraph execution asynchronously
        final_state = await graph.ainvoke(initial_state, config=config)
        end_to_end_ms = (perf_counter() - started_at) * 1000

        run_id = get_run_id(payload)
        payload_for_storage = payload.model_copy(update={"run_id": run_id})
        background_tasks.add_task(
            persist_and_evaluate_run,
            collection=request.app.state.run_collection,
            payload=payload_for_storage,
            final_state=final_state,
            end_to_end_ms=end_to_end_ms,
        )
        
        # 4. Extract the last message generated by your LLM node
        last_message = final_state["messages"][-1]
        
        return {
            "status": "success",
            "run_id": run_id,
            "active_process": payload.process_type,
            "response": last_message.content,
            "token_usage": final_state.get(
                "token_usage",
                {"input": 0, "output": 0, "total": 0},
            ),
            "token_breakdown": {
                "measurement_version": 2,
                "calls": final_state.get("model_calls", []),
                "by_phase": phase_usage(final_state.get("model_calls", [])),
                "context": final_state.get("context_tokens", {}),
            },
            "selected_tools": final_state.get("selected_tools", []),
            "loaded_skills": final_state.get("loaded_skills", []),
        }
        
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to process agent workflow execution stream: {str(e)}"
        )
